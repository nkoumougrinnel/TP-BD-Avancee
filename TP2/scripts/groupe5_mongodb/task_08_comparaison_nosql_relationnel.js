#!/usr/bin/env mongosh
print("=== Task 8 : Comparaison NoSQL vs Relationnel ===");
print("1. MODÈLE DOCUMENT (MongoDB) :");
print("   Structure : Un document par étudiant contenant TOUTES les informations :");
print("   │");
print("   │   _id, matricule, nom, prénom, email");
print("   │   filières[], coordonnées{adresse, ville, cp}");
print("   │   téléphone, niveau, spécialité");
print("   │   certifications[] (optionnel)");
print("   │   stages[] (optionnel)");
print("   │   documentsJustificatifs[] (optionnel)");
print("   └─────────────────────────────────────────────────────────────");
print("   Avantage : Toutes les données d'un étudiant en un seul endroit");
print("              ➔ Pas de JOINs, lecture rapide, schema flexible");
print("              ➔ Facile à faire évoluer (nouveaux champs = pas de migration)");
print("   Inconvénient : Redondance potentielle si même info utilisée ailleurs");
print("                ➔ Mise à jour plus complexe si info partagée");

print("\n2. MODÈLE RELATIONNEL (SQL) - Approche équivalente :");
print("   Table 'etudiants' :");
print("   │ id, matricule, nom, prénom, email, niveau, spécialité");
print("   └─────────────────────────────────────────────────────────");
print("   Table 'filieres' :");
print("   │ id, libelle, code, departement");
print("   └─────────────────────────────────────────────────────────");
print("   Table 'certifications' :");
print("   │ id, etudiant_id, nom, organisme, date_obtention, niveau");
print("   └─────────────────────────────────────────────────────────");
print("   Table 'stages' :");
print("   │ id, etudiant_id, entreprise, periode, domaine, statut");
print("   └─────────────────────────────────────────────────────────");
print("   Table 'documents_justificatifs' :");
print("   │ id, etudiant_id, type, date_obtention, url_stockage");
print("   └─────────────────────────────────────────────────────────");
print("   Relations :");
print("   │ etudiants.id ───► filieres.id (N-M via table junction)");
print("   │ etudiants.id ───► certifications.etudiant_id");
print("   │ etudiants.id ───► stages.etudiant_id");
print("   │ etudiants.id ───► documents_justificatifs.etudiant_id");
print("   └─────────────────────────────────────────────────────────");
print("   Avantages :");
print("   │ ✅ Intégrité référentielle (clés étrangères)");
print("   │ ✅ Pas de redondance données");
print("   │ ✅ Transactions ACID garanties");
print("   │ ✅ Standards SQL partout");
print("   │ ✅ Requêtes très précises avec indices");
print("   └─────────────────────────────────────────────────────────");
print("   Inconvénients :");
print("   │ ❌ JOINs complexes pour tout récupérer");
print("   │ ❌ Schéma rigide (migrations nécessaires)");
print("   │ ❌ Nouvelle étude = création de tables/colonnes");
print("   │ ❌ Insertion répartie sur plusieurs tables");
print("   └─────────────────────────────────────────────────────────");

print("\n3. EXEMPLE DE RÉQUÊTE : Récupérer un étudiant avec ses certifications et stages");
print("   ▸ MongoDB :");
print("   │ var e = db.etudiants.findOne({matricule: 'E2024001'});");
print("   │ print(e.nom + ' a ' + e.certifications.length + ' certifications');");
print("   │ print('et ' + e.stages.length + ' stages');");
print("   └── 1 requête, 1 document");
print("\n   ▸ SQL :");
print("   │ SELECT e.nom, COUNT(DISTINCT c.id) as nb_certs,");
print("   │        COUNT(DISTINCT s.id) as nb_stages");
print("   │ FROM étudiants e");
print("   │ LEFT JOIN certifications c ON e.id = c.etudiant_id");
print("   │ LEFT JOIN stages s ON e.id = s.etudiant_id");
print("   │ WHERE e.matricule = 'E2024001'");
print("   │ GROUP BY e.id");
print("   └── 1 requête avec JOINs, normalisation mais plus complexe");

print("\n4. SCÉNARIO SPÉCIFIQUE AU TP :");
print("   ▸ Situation : Un étudiant change de filière");
print("   ▸ MongoDB :");
print("   │ db.etudiants.updateOne({matricule: 'E2024003'}, {$set: {filieres: ['Nouvelle Filière']}});");
print("   │ ✅ 1 ligne modifiée, pas de contrainte étrangère");
print("   ▸ SQL :");
print("   │ UPDATE étudiants SET filiere_id = NEW_ID WHERE id = STUDENT_ID;");
print("   │ ✅ OK si clé étrangère valide, ❌ ERREUR si contrainte violated");
print("   └── MongoDB plus flexible pour les changements de schema");

print("\n5. CONCLUSION :");
print("   ▸ Pour ce TP (étudiants avec informations variables) :");
print("   │ ✅ MongoDB : Idéal pour schémas flexibles, variable par formation");
print("   │ ✅ SQL : Meilleur si schéma stable, intégrité stricte requise");
print("   │ ▸ Le choix dépend du cas d'usage :");
print("   │    • MongoDB : Étudiants formation variable, certifications diverse");
print("   │    • SQL : Structure stable, transactions critiques, reporting standard");
print("   ▸ TP2 recommande MongoDB pour cette utilisation universitaire");
print("   └───────────────────────────────────────────────────────────────");